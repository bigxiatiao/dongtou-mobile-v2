/* node home-map-behavior.test.js：只验证首页消费的业务结果，不复制状态机。 */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const sandbox = { window: {} };
for (const name of ['collection-data','transfer-data','transfer-store','home-map-data']) vm.runInNewContext(fs.readFileSync(`${__dirname}/${name}.js`, 'utf8'), sandbox);
const { CollectionStore: collection, TransferStore: transfer, TransferDemoData: data, HomeMapData: map } = sandbox.window;
const items = mode => map.groups(mode).flatMap(group => group.items);
assert.ok(items('task').length > 0);
assert.deepEqual(new Set(items('task').map(item => item.status)), new Set(['待转移','待复核','异常跟进']));
assert.ok(map.groups('task').some(group => group.items.length > 1), '同址多人可展开选择');
assert.deepEqual(new Set(map.groups('task').map(group => group.color)), new Set(['red','orange','yellow']), '默认地图同时有红橙黄三种点位');
assert.ok(map.groups('task').filter(group => group.items.some(item => item.status === '异常跟进')).every(group => group.color === 'red'), '聚合优先异常红色');
assert.deepEqual(new Set(items('collection').map(item => item.color)), new Set(['red','green']));
assert.equal(items('collection').length, collection.addresses().length);
assert.ok(items('collection').every(item => ['door','building'].includes(item.type)));
collection.setScope('dp04');
assert.equal(items('task').length, 0);
assert.equal(items('collection').length, 0);
collection.setScope('dt');
assert.ok(items('task').some(item => item.id === 'P03'), '父级范围包含下级范围');
collection.setScope('dp03');
assert.ok(!items('task').some(item => item.id === 'P03'), '网格不会借用其他范围任务');
const person = transfer.task('P01');
person.transfer.status = '转移途中';
assert.ok(!items('task').some(item => item.id === person.id), '离开三类状态的任务从地图消失');
person.transfer.status = '异常跟进';
assert.equal(items('task').find(item => item.id === person.id).color, 'red', '任务变更刷新颜色');
const door = collection.get('door','door-18');
assert.equal(collection.setStatus('door',door.id,'verified').status, 'verified');
assert.equal(items('collection').find(item => item.id === door.id).color, 'green', '采集核查刷新为绿色');
data.action.status = '已结束';
assert.equal(items('task').length, 0, '不显示已结束行动的任务');
assert.ok(items('collection').length, '采集不依赖行动状态');
console.log('PASS: 首页地图状态范围、聚合、业务变更与行动隔离');
